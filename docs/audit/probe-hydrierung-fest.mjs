// Befund A2, deterministisch: JS wird zurückgehalten, bis getippt ist; dann Hydrierung. Aufruf: node docs/audit/probe-hydrierung-fest.mjs
import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome' })
const page = await (await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, locale: 'de-AT' })).newPage()
let freigeben
const halt = new Promise((r) => (freigeben = r))
await page.route('**/assets/index-*.js', async (r) => { await halt; await r.continue() })
await page.goto('http://localhost:4173/', { waitUntil: 'commit' })
await page.locator('#anfrage form').waitFor()
const a = page.locator('#anfrage')
await page.locator('section[aria-labelledby="schnellwahl-titel"] a[data-gewerk="installateur"]').tap()
await a.getByLabel(/^Name/).tap(); await page.keyboard.type('Maria Huber')
await a.getByLabel(/^Telefon/).tap(); await page.keyboard.type('0664 1234567')
await a.getByLabel(/^Gewerk/).selectOption('elektro')
console.log('vor Hydrierung:', JSON.stringify({ name: await a.getByLabel(/^Name/).inputValue(), tel: await a.getByLabel(/^Telefon/).inputValue(), gewerk: await a.getByLabel(/^Gewerk/).inputValue() }))
freigeben()
await page.waitForFunction(() => document.documentElement.hasAttribute('data-hydriert'))
await page.waitForTimeout(1000)
console.log('nach Hydrierung:', JSON.stringify({ name: await a.getByLabel(/^Name/).inputValue(), tel: await a.getByLabel(/^Telefon/).inputValue(), gewerk: await a.getByLabel(/^Gewerk/).inputValue() }))
await a.getByLabel(/^PLZ und Ort/).tap(); await page.keyboard.type('1020 Wien')
await a.getByRole('checkbox').tap()
await a.getByRole('button', { name: 'Anfrage senden' }).tap()
await page.waitForTimeout(2000)
console.log('Fehler nach Senden:', JSON.stringify(await a.locator('[id$="-fehler"]').allInnerTexts()), 'Erfolg:', await a.getByText(/Anfragenummer/).isVisible())
await b.close()

// Befund A2: Eingaben im Formular vor der Hydrierung (Slow 4G + CPU 4×). Aufruf: node docs/audit/probe-hydrierung.mjs [lauf]
import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome' })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, locale: 'de-AT' })
const page = await ctx.newPage()
const cdp = await ctx.newCDPSession(page)
await cdp.send('Network.enable')
await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 562.5, downloadThroughput: (1474.56 * 1024) / 8, uploadThroughput: (675 * 1024) / 8 })
await cdp.send('Emulation.setCPUThrottlingRate', { rate: 4 })
await page.goto('http://localhost:4173/', { waitUntil: 'commit' })
const a = page.locator('#anfrage')
await page.locator('section[aria-labelledby="schnellwahl-titel"] a[data-gewerk="installateur"]').tap()
await a.getByLabel(/^Name/).tap(); await page.keyboard.type('Maria Huber')
const vorHyd = await page.evaluate(() => document.documentElement.hasAttribute('data-hydriert'))
await page.waitForFunction(() => document.documentElement.hasAttribute('data-hydriert'))
console.log('Name getippt vor Hydrierung:', !vorHyd)
console.log('Feldinhalt nach Hydrierung:', JSON.stringify(await a.getByLabel(/^Name/).inputValue()))
console.log('Gewerk nach Hydrierung:', JSON.stringify(await a.getByLabel(/^Gewerk/).inputValue()))
await a.getByLabel(/^Telefon/).tap(); await page.keyboard.type('0664 1234567')
await a.getByLabel(/^PLZ und Ort/).tap(); await page.keyboard.type('1020 Wien')
await a.getByLabel(/^Gewerk/).selectOption('installateur')
await a.getByRole('checkbox').tap()
await a.getByRole('button', { name: 'Anfrage senden' }).tap()
await page.waitForTimeout(3000)
console.log('Feldinhalt Name nach Senden:', JSON.stringify(await a.getByLabel(/^Name/).inputValue().catch(() => '(Formular ersetzt)')))
console.log('Fehlertexte:', JSON.stringify(await a.locator('[id$="-fehler"]').allInnerTexts()))
console.log('Erfolg sichtbar:', await a.getByText(/Anfragenummer/).isVisible())
console.log('Fokus auf:', await page.evaluate(() => document.activeElement?.id))
await page.screenshot({ path: `docs/audit/belege/${process.argv[2] ?? 'vorher'}/a-s2-eingabe-vor-hydrierung.png` })
await b.close()
